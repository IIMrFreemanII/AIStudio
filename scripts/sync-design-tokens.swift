#!/usr/bin/env swift
// Generates Sources/MLXComfyApp/Design/MGTokens.swift from the MetalGraphics Frosted Glass design system's tokens.
//
//   swift scripts/sync-design-tokens.swift [design/metalgraphics/tokens.json] [Sources/MLXComfyApp/Design/MGTokens.swift]
//
// To re-sync: copy the design system's `project/tokens.json` over design/metalgraphics/tokens.json, run this, rebuild.
// Colours become dynamic NSColors (light and dark), text styles, spacing, radii, shadows and glass parameters Swift
// constants. The code-editor and syntax colours aren't used by the app and are skipped.
import Foundation

let args = CommandLine.arguments
let input = URL(fileURLWithPath: args.count > 1 ? args[1] : "design/metalgraphics/tokens.json")
let output = URL(fileURLWithPath: args.count > 2 ? args[2] : "Sources/MLXComfyApp/Design/MGTokens.swift")

guard let root = try JSONSerialization.jsonObject(with: Data(contentsOf: input)) as? [String: Any] else {
    fatalError("\(input.path) isn't a JSON object")
}

func camel(_ name: String, dropping prefix: String) -> String {
    let parts = name.dropFirst(prefix.count).split(separator: "-").map(String.init)
    guard let first = parts.first else { return name }
    let id = first + parts.dropFirst().map { $0.prefix(1).uppercased() + $0.dropFirst() }.joined()
    return id.first!.isNumber ? "_" + id : id
}

/// `#rgb`, `#rrggbb`, `#rrggbbaa` → (r, g, b, a) in 0…1.
func rgba(_ hex: String) -> (Double, Double, Double, Double)? {
    var h = hex.trimmingCharacters(in: .whitespaces)
    guard h.hasPrefix("#") else { return nil }
    h.removeFirst()
    if h.count == 3 || h.count == 4 { h = h.map { "\($0)\($0)" }.joined() }
    guard h.count == 6 || h.count == 8, let v = UInt64(h, radix: 16) else { return nil }
    let n = h.count == 6 ? (v << 8) | 0xff : v
    return (Double((n >> 24) & 0xff) / 255, Double((n >> 16) & 0xff) / 255, Double((n >> 8) & 0xff) / 255, Double(n & 0xff) / 255)
}

func literal(_ c: (Double, Double, Double, Double)) -> String {
    String(format: "(%.4f, %.4f, %.4f, %.4f)", c.0, c.1, c.2, c.3)
}

func px(_ v: Any) -> Double {
    if let d = v as? Double { return d }
    if let i = v as? Int { return Double(i) }
    let s = String(describing: v).replacingOccurrences(of: "px", with: "")
    return Double(s) ?? 0
}

var out = """
// Generated by scripts/sync-design-tokens.swift from design/metalgraphics/tokens.json (MetalGraphics Frosted Glass).
// Don't edit by hand: change the tokens and run the script again.
import AppKit
import SwiftUI

// swiftlint:disable all

"""

// MARK: colours
let color = root["color"] as! [String: Any]
let tokens = color["tokens"] as! [[String: Any]]
var byName: [String: [String: Any]] = [:]
for t in tokens { byName[t["name"] as! String] = t }
func resolve(_ value: Any, theme: String, depth: Int = 0) -> (Double, Double, Double, Double)? {
    let v: Any = (value as? [String: Any]).map { $0[theme] ?? $0["light"] as Any } ?? value
    guard let s = v as? String else { return nil }
    if s.hasPrefix("{"), s.hasSuffix("}"), depth < 8, let target = byName[String(s.dropFirst().dropLast())] {
        return resolve(target["value"]!, theme: theme, depth: depth + 1)
    }
    return rgba(s)
}

var colorLines: [String] = []
var nsLines: [String] = []
for t in tokens {
    let name = t["name"] as! String
    guard !name.hasPrefix("mg-editor-"), !name.hasPrefix("mg-syntax-") else { continue }
    let prefix = name.hasPrefix("mg-color-") ? "mg-color-" : "mg-"
    let id = camel(name, dropping: prefix)
    guard let light = resolve(t["value"]!, theme: "light") else { continue }
    let dark = resolve(t["value"]!, theme: "dark") ?? light
    let usage = (t["usage"] as? String).map { "    /// \($0)\n" } ?? ""
    nsLines.append("\(usage)    static let \(id) = MGColor.dynamic(\"\(name)\", light: \(literal(light)), dark: \(literal(dark)))")
    colorLines.append("\(usage)    static let \(id) = Color(nsColor: MGColor.\(id))")
}
out += """
/// The design system's colours as dynamic AppKit colours (light and dark values).
enum MGColor {
    static func dynamic(_ name: String, light: (Double, Double, Double, Double), dark: (Double, Double, Double, Double)) -> NSColor {
        NSColor(name: NSColor.Name(name)) { appearance in
            let c = appearance.bestMatch(from: [.aqua, .darkAqua]) == .darkAqua ? dark : light
            return NSColor(srgbRed: c.0, green: c.1, blue: c.2, alpha: c.3)
        }
    }

\(nsLines.joined(separator: "\n"))
}

/// The design system's colours for SwiftUI: `MG.label`, `MG.accent`, `MG.hueFolder`…
enum MG {
\(colorLines.joined(separator: "\n"))
}


"""

// MARK: type
let type = root["type"] as! [String: Any]
var styleLines: [String] = []
for g in type["groups"] as! [[String: Any]] {
    for s in g["styles"] as! [[String: Any]] {
        let id = camel(s["name"] as! String, dropping: "mg-font-")
        let weight = Int(px(s["fontWeight"] ?? 400))
        let usage = (s["usage"] as? String).map { "    /// \($0)\n" } ?? ""
        styleLines.append("\(usage)    static let \(id) = MGTextStyle(size: \(px(s["fontSize"]!)), weight: \(weight))")
    }
}
out += """
/// The design system's text styles (JetBrains Mono): `MGType.body.font`, `MGType.headline.nsFont`…
enum MGType {
\(styleLines.joined(separator: "\n"))
}


"""

// MARK: spacing, radius
func lengths(_ family: String, prefix: String, type: String) -> String {
    guard let f = root[family] as? [String: Any], let ts = f["tokens"] as? [[String: Any]] else { return "" }
    let lines = ts.map { t -> String in
        let usage = (t["usage"] as? String).map { "    /// \($0)\n" } ?? ""
        return "\(usage)    static let \(camel(t["name"] as! String, dropping: prefix)): CGFloat = \(px(t["value"]!))"
    }
    return "enum \(type) {\n\(lines.joined(separator: "\n"))\n}\n\n"
}
out += "/// Spacing steps.\n" + lengths("spacing", prefix: "mg-space-", type: "MGSpace")
out += "/// Corner radii.\n" + lengths("radius", prefix: "mg-radius-", type: "MGRadius")

// MARK: shadows: "x y blur spread colour" per theme
if let f = root["shadow"] as? [String: Any], let ts = f["tokens"] as? [[String: Any]] {
    func parts(_ s: String) -> (Double, Double, Double, (Double, Double, Double, Double)) {
        let p = s.split(separator: " ").map(String.init)
        return (px(p[0]), px(p[1]), px(p[2]), rgba(p.last!) ?? (0, 0, 0, 0.2))
    }
    let lines = ts.map { t -> String in
        let v = t["value"] as? [String: Any]
        let light = parts((v?["light"] as? String) ?? (t["value"] as? String) ?? "0 0 0 0 #00000000")
        let dark = parts((v?["dark"] as? String) ?? (v?["light"] as? String) ?? "0 0 0 0 #00000000")
        let id = camel(t["name"] as! String, dropping: "mg-shadow-")
        return "    static let \(id) = MGShadowSpec(x: \(light.0), y: \(light.1), blur: \(light.2), "
            + "color: Color(nsColor: MGColor.dynamic(\"\(t["name"] as! String)\", light: \(literal(light.3)), dark: \(literal(dark.3)))))"
    }
    out += "/// Shadows: only for what floats (knobs, popovers, sheets, floating panels).\nenum MGShadow {\n\(lines.joined(separator: "\n"))\n}\n\n"
}

// MARK: glass blur and saturation per role
if let f = root["glass"] as? [String: Any], let ts = f["tokens"] as? [[String: Any]] {
    let lines = ts.map { "    static let \(camel($0["name"] as! String, dropping: "mg-glass-")): CGFloat = \(px($0["value"]!))" }
    out += "/// Glass: backdrop blur radius and saturation per role.\nenum MGGlassMetrics {\n\(lines.joined(separator: "\n"))\n}\n"
}

try out.write(to: output, atomically: true, encoding: .utf8)
print("wrote \(output.path): \(nsLines.count) colours, \(styleLines.count) text styles")
